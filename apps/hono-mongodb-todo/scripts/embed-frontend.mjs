import { readFile, readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const appRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const distRoot = path.join(appRoot, 'frontend', 'dist')
const assetsRoot = path.join(distRoot, 'assets')
const generatedFile = path.join(appRoot, 'generated', 'frontend-assets.ts')

const assetNames = (await readdir(assetsRoot)).sort()
const scriptNames = assetNames.filter((name) => name.endsWith('.js'))
const styleNames = assetNames.filter((name) => name.endsWith('.css'))

if (scriptNames.length !== 1 || styleNames.length !== 1) {
  throw new Error(
    `Expected one JavaScript and one CSS asset, found scripts=${scriptNames.length}, styles=${styleNames.length}`
  )
}

const scriptPath = `/assets/${scriptNames[0]}`
const stylePath = `/assets/${styleNames[0]}`
const [html, script, style] = await Promise.all([
  readFile(path.join(distRoot, 'index.html'), 'utf8'),
  readFile(path.join(assetsRoot, scriptNames[0]), 'utf8'),
  readFile(path.join(assetsRoot, styleNames[0]), 'utf8')
])

const generated = [
  '// Generated by scripts/embed-frontend.mjs. Do not edit by hand.',
  `export const FRONTEND_HTML: string = ${JSON.stringify(html)}`,
  `export const FRONTEND_SCRIPT_PATH: string = ${JSON.stringify(scriptPath)}`,
  `export const FRONTEND_SCRIPT: string = ${JSON.stringify(script)}`,
  `export const FRONTEND_STYLE_PATH: string = ${JSON.stringify(stylePath)}`,
  `export const FRONTEND_STYLE: string = ${JSON.stringify(style)}`,
  ''
].join('\n')

await writeFile(generatedFile, generated, 'utf8')
console.log(`Embedded ${html.length + script.length + style.length} UTF-16 code units into ${generatedFile}`)
