import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'

const require = createRequire(import.meta.url)
const db = require('mime-db')
const { version: dbVersion } = require('mime-db/package.json')
const { version: typesVersion } = require('mime-types/package.json')
const mimeScore = require('mime-types/mimeScore')

const output = path.resolve(import.meta.dirname, '../../runtime/node/nest/shims/mime-db/db.generated.ts')

const extensionTypes = new Map()
const typeExtensions = new Map()
const typeCharsets = new Map()
for (const type of Object.keys(db).sort()) {
  const entry = db[type]
  if (entry.charset) typeCharsets.set(type, entry.charset)
  const extensions = entry.extensions
  if (!extensions || extensions.length === 0) continue
  typeExtensions.set(type, [...extensions])
  for (const extension of extensions) {
    const current = extensionTypes.get(extension)
    const currentScore = current ? mimeScore(current, db[current].source) : 0
    const nextScore = mimeScore(type, db[type].source)
    extensionTypes.set(extension, currentScore > nextScore ? current : type)
  }
}

const quote = (value) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const record = (map, render) =>
  [...map.entries()]
    .sort(([left], [right]) => (left < right ? -1 : left > right ? 1 : 0))
    .map(([key, value]) => `  ${quote(key)}: ${render(value)},`)
    .join('\n')

const text = `// Generated by tools/nest/generate-mime-db.mjs from mime-db ${dbVersion}, with
// mime-types ${typesVersion}'s extension tie-break (mimeScore). DO NOT EDIT;
// re-run the generator (\`npm run generate\` in tools/nest) after changing the pin.
//
// Only what the three callers in the vendored platform-node sources can ask
// for: NodeResponse.type(ext), type-is' short-name lookup and send's
// Content-Type by file extension. Types without extensions are not listed
// because no lookup can reach them.

export const MIME_DB_VERSION = ${quote(dbVersion)}

/** Extension (without the dot, lower case) to its preferred media type: mime-types' \`types\`. */
export const extensionTypes: { [extension: string]: string } = {
${record(extensionTypes, quote)}
}

/** Media type to its extensions, in mime-db order: mime-types' \`extensions\`. */
export const typeExtensions: { [type: string]: string[] } = {
${record(typeExtensions, (list) => `[${list.map(quote).join(', ')}]`)}
}

/** Media types for which mime-db states a default charset. */
export const typeCharsets: { [type: string]: string } = {
${record(typeCharsets, quote)}
}
`

if (process.argv.includes('--check')) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : null
  if (current !== text) {
    console.error(`${path.relative(process.cwd(), output)} is out of date; run \`npm run generate\` in tools/nest`)
    process.exit(1)
  }
  console.log(`${path.relative(process.cwd(), output)} is current (mime-db ${dbVersion})`)
} else {
  fs.mkdirSync(path.dirname(output), { recursive: true })
  fs.writeFileSync(output, text)
  console.log(`wrote ${path.relative(process.cwd(), output)}: ${extensionTypes.size} extensions, ${typeExtensions.size} types, ${typeCharsets.size} charsets`)
}
