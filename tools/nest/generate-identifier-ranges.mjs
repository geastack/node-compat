import fs from 'node:fs'
import path from 'node:path'

const output = path.resolve(import.meta.dirname, '../../runtime/node/nest/shims/path-to-regexp/identifier.generated.ts')
const unicodeVersion = process.versions.unicode

const idStart = /^\p{ID_Start}$/u
const idContinue = /^\p{ID_Continue}$/u
const assigned = /^\p{Assigned}$/u

const rangesOf = (pattern) => {
  const ranges = []
  for (let code = 0; code <= 0x10ffff; code++) {
    if (code >= 0xd800 && code <= 0xdfff) continue
    if (!pattern.test(String.fromCodePoint(code))) continue
    const last = ranges.length - 1
    if (last >= 1 && ranges[last] === code - 1) ranges[last] = code
    else ranges.push(code, code)
  }
  return ranges
}

const render = (ranges) => {
  const lines = []
  for (let i = 0; i < ranges.length; i += 16) lines.push('  ' + ranges.slice(i, i + 16).join(', ') + ',')
  return lines.join('\n')
}

const text = `// Generated by tools/nest/generate-identifier-ranges.mjs from Unicode ${unicodeVersion}. DO NOT EDIT;
// re-run the generator (\`npm run generate\` in tools/nest) on a Node with a newer Unicode.
//
// path-to-regexp 8.4.2 reads parameter names with /[$_\\p{ID_Start}]/u and
// /[$\\u200c\\u200d\\p{ID_Continue}]/u. The compiled target has no Unicode property
// escapes, so the same sets are listed here as inclusive [first, last] code point pairs.

export const IDENTIFIER_UNICODE_VERSION = '${unicodeVersion}'

export const idStartRanges: number[] = [
${render(rangesOf(idStart))}
]

export const idContinueRanges: number[] = [
${render(rangesOf(idContinue))}
]
`

const recordedRanges = (current, name) =>
  (new RegExp(`export const ${name}: number\\[\\] = \\[([^\\]]*)\\]`).exec(current)?.[1] ?? '')
    .split(',')
    .map((value) => value.trim())
    .filter((value) => value !== '')
    .map(Number)

const disagreements = (ranges, pattern) => {
  const listed = new Uint8Array(0x110000)
  for (let i = 0; i + 1 < ranges.length; i += 2) listed.fill(1, ranges[i], ranges[i + 1] + 1)
  let count = 0
  for (let code = 0; code <= 0x10ffff; code++) {
    if (code >= 0xd800 && code <= 0xdfff) continue
    const char = String.fromCodePoint(code)
    if (assigned.test(char) && (listed[code] === 1) !== pattern.test(char)) count++
  }
  return count
}

if (process.argv.includes('--check')) {
  const current = fs.existsSync(output) ? fs.readFileSync(output, 'utf8') : ''
  const recorded = /IDENTIFIER_UNICODE_VERSION = '([^']+)'/.exec(current)?.[1]
  if (recorded !== undefined && recorded !== unicodeVersion) {
    const differing = disagreements(recordedRanges(current, 'idStartRanges'), idStart) + disagreements(recordedRanges(current, 'idContinueRanges'), idContinue)
    if (differing > 0) {
      console.error(`${path.relative(process.cwd(), output)} (Unicode ${recorded}) disagrees with this Node's Unicode ${unicodeVersion} on ${differing} assigned code point(s); run \`npm run generate\` in tools/nest`)
      process.exit(1)
    }
    console.log(`${path.relative(process.cwd(), output)} (Unicode ${recorded}) agrees with this Node's Unicode ${unicodeVersion} on every code point it assigns`)
  } else if (current !== text) {
    console.error(`${path.relative(process.cwd(), output)} is out of date; run \`npm run generate\` in tools/nest`)
    process.exit(1)
  } else {
    console.log(`${path.relative(process.cwd(), output)} is current (Unicode ${unicodeVersion})`)
  }
} else {
  fs.writeFileSync(output, text)
  console.log(`wrote ${path.relative(process.cwd(), output)}`)
}
